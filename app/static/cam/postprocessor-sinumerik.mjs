import { CAM_STATUS, issue } from './contracts.mjs';

function ncNumber(value, digits = 3) {
  const number = Number(value);
  if (!Number.isFinite(number)) return null;
  return number.toFixed(digits).replace(/\.0+$/, '').replace(/(\.\d*?)0+$/, '$1');
}

function fnv1a32(text) {
  let hash = 0x811c9dc5;
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, '0');
}

function toolForOperation(plan, operation) {
  if (operation.kind === 'threading') return plan.threading.feature.toolId;
  if (operation.kind === 'drilling') return plan.drilling.feature.toolId;
  if (operation.kind === 'radial_drilling') return plan.radialDrilling.feature.toolId;
  if (operation.kind === 'milling_af') return plan.millingAf.feature.toolId;
  if (operation.kind === 'milling_pocket') return plan.millingPocket.feature.toolId;
  if (operation.kind === 'cutoff') return plan.cutoff.feature.toolId;
  return operation.kind === 'finish_turning' ? 'T2' : 'T1';
}

function toolNumber(toolId) {
  const match = String(toolId || '').match(/T\s*(\d+)/i);
  return match ? Number(match[1]) : null;
}

export function validateSinumerikExport(plan, config) {
  const errors = [];
  if (!config.confirmed) errors.push(issue('POST_CONFIG_UNCONFIRMED', 'Машинные коды и формат программы должны быть подтверждены для конкретного станка.', 'error', 'export'));
  if (!Number.isFinite(config.safeParkX) || !Number.isFinite(config.safeParkZ)) errors.push(issue('POST_SAFE_PARK_REQUIRED', 'Нужны подтверждённые координаты безопасной парковки X/Z.', 'error', 'export'));
  if (Number.isFinite(config.safeParkX) && (config.safeParkX < plan.machineSetup.limits.xMin || config.safeParkX > plan.machineSetup.limits.xMax)
    || Number.isFinite(config.safeParkZ) && (config.safeParkZ < plan.machineSetup.limits.zMin || config.safeParkZ > plan.machineSetup.limits.zMax)) {
    errors.push(issue('POST_SAFE_PARK_OUTSIDE_LIMITS', 'Безопасная парковка выходит за подтверждённые ходы станка.', 'error', 'export'));
  }
  if (plan.collision?.status !== CAM_STATUS.EVALUATED_LIMITED || !plan.collision?.safe) {
    errors.push(issue('POST_COLLISION_GATE', 'Экспорт разрешён только после успешной проверки ограничивающих оболочек.', 'error', 'export'));
  }
  if (plan.unsupportedOperations?.length) errors.push(issue('POST_UNSUPPORTED_ROUTE', 'Маршрут содержит неподдерживаемые операции; удалите их или реализуйте до экспорта.', 'error', 'export'));
  const liveToolRequired = [plan.millingAf, plan.millingPocket, plan.radialDrilling].some(item => item?.status === CAM_STATUS.SUPPORTED);
  if (liveToolRequired) {
    for (const [code, value, label] of [
      ['POST_C_CLAMP_REQUIRED', config.cAxisClamp, 'зажим C'],
      ['POST_C_UNCLAMP_REQUIRED', config.cAxisUnclamp, 'разжим C'],
      ['POST_LIVE_TOOL_ON_REQUIRED', config.liveToolOn, 'включение приводного инструмента'],
      ['POST_LIVE_TOOL_OFF_REQUIRED', config.liveToolOff, 'выключение приводного инструмента'],
    ]) if (!String(value || '').trim()) errors.push(issue(code, `Не задан машинный код: ${label}.`, 'error', 'export'));
  }
  return { status: errors.length ? CAM_STATUS.BLOCKED : CAM_STATUS.SUPPORTED, errors };
}

export class Sinumerik828DPostprocessor {
  generate(plan, config) {
    const validation = validateSinumerikExport(plan, config);
    if (validation.errors.length) {
      return { status: CAM_STATUS.BLOCKED, controller: 'SINUMERIK 828D', dialect: 'SIEMENS', errors: validation.errors, lines: [], text: '', trace: [] };
    }
    const lines = [`%_N_${config.programName}_MPF`, '; GENERATED BY PERSONAL AI CLIENT PRO', '; VERIFY IN SINUTRAIN / CONTROL AND RUN DRY-RUN', 'G18 G90 G94 DIAMON', config.workOffset];
    const trace = [];
    let sequence = 10;
    let activeTool = null;
    let liveToolActive = false;
    const emit = (code, meta = {}) => {
      const line = `N${sequence} ${code}`;
      lines.push(line);
      trace.push({ lineNumber: sequence, line, ...meta });
      sequence += 10;
    };
    for (const operation of plan.operations) {
      const toolId = toolForOperation(plan, operation);
      const number = toolNumber(toolId);
      if (!number) throw new Error(`Некорректный идентификатор инструмента ${toolId}`);
      if (activeTool !== number) {
        if (liveToolActive) { emit(config.liveToolOff, { role: 'live_tool_off' }); liveToolActive = false; }
        emit('M5', { role: 'spindle_stop' });
        emit(`T${number} D1`, { role: 'tool_change', toolId });
        activeTool = number;
        const rpm = operation.kind === 'threading' ? plan.threading.feature.rpm
          : operation.kind === 'drilling' ? plan.drilling.feature.rpm
            : operation.kind === 'radial_drilling' ? plan.radialDrilling.feature.rpm
              : operation.kind === 'milling_af' ? plan.millingAf.feature.rpm
                : operation.kind === 'milling_pocket' ? plan.millingPocket.feature.rpm
                  : operation.kind === 'cutoff' ? plan.cutoff.feature.rpm
                    : plan.turning.parameters.rpm;
        if (['milling_af','milling_pocket','radial_drilling'].includes(operation.kind)) {
          emit(config.liveToolOn.replaceAll('{RPM}', ncNumber(rpm, 0)), { role: 'live_tool_on', rpm });
          liveToolActive = true;
        } else {
          emit(`S${ncNumber(rpm, 0)} M3`, { role: 'main_spindle_on', rpm });
        }
        if (config.coolantOn) emit(config.coolantOn, { role: 'coolant_on' });
      }
      emit(`; ${operation.name}`, { operationId: operation.id, role: 'operation_comment' });
      for (let index = operation.moveStart; index <= operation.moveEnd; index += 1) {
        const move = plan.moves[index];
        if (!move || move.operationId !== operation.id) continue;
        if (move.motion === 'index') {
          if (liveToolActive) { emit(config.liveToolOff, { operationId: operation.id, role: 'live_tool_pause' }); liveToolActive = false; }
          emit('M5', { operationId: operation.id, role: 'spindle_stop_for_index' });
          emit(config.cAxisUnclamp, { operationId: operation.id, role: 'c_unclamp' });
          emit(`SPOS=AC(${ncNumber(move.to.c, 3)})`, { operationId: operation.id, moveId: move.id, role: move.role });
          emit(config.cAxisClamp, { operationId: operation.id, role: 'c_clamp' });
          const liveRpm = operation.kind === 'radial_drilling' ? plan.radialDrilling.feature.rpm : operation.kind === 'milling_pocket' ? plan.millingPocket.feature.rpm : plan.millingAf.feature.rpm;
          emit(config.liveToolOn.replaceAll('{RPM}', ncNumber(liveRpm, 0)), { operationId: operation.id, role: 'live_tool_resume' });
          liveToolActive = true;
          continue;
        }
        const words = [];
        if (Number.isFinite(move.to.x)) words.push(`X${ncNumber(move.to.x)}`);
        if (Number.isFinite(move.to.y) && Math.abs(move.to.y) > 1e-9) words.push(`Y${ncNumber(move.to.y)}`);
        if (Number.isFinite(move.to.z)) words.push(`Z${ncNumber(move.to.z)}`);
        if (move.motion === 'thread') {
          emit(`G33 ${words.filter(word => word.startsWith('Z')).join(' ')} K${ncNumber(move.pitch)}`, { operationId: operation.id, moveId: move.id, role: move.role, synchronized: true });
        } else if (move.motion === 'rapid') {
          emit(`G0 ${words.join(' ')}`, { operationId: operation.id, moveId: move.id, role: move.role });
        } else if (move.motion === 'feed') {
          emit(`G1 ${words.join(' ')} F${ncNumber(move.feedRate, 3)}`, { operationId: operation.id, moveId: move.id, role: move.role });
        }
      }
    }
    if (liveToolActive) emit(config.liveToolOff, { role: 'live_tool_off_final' });
    if (config.coolantOff) emit(config.coolantOff, { role: 'coolant_off' });
    emit('M5', { role: 'spindle_stop_final' });
    emit(`G0 X${ncNumber(config.safeParkX)} Z${ncNumber(config.safeParkZ)}`, { role: 'machine_safe_position_confirmed' });
    emit('M30', { role: 'program_end' });
    const text = `${lines.join('\n')}\n`;
    const mappedMoves = new Set(trace.filter(item => item.moveId).map(item => item.moveId));
    const cuttingMoves = plan.moves.filter(move => move.cutting);
    const missingCuttingMoves = cuttingMoves.filter(move => !mappedMoves.has(move.id));
    const errors = [];
    if (missingCuttingMoves.length) errors.push(issue('POST_TRACE_INCOMPLETE', `Не отображено режущих движений: ${missingCuttingMoves.length}.`, 'error', 'export'));
    if (!text.includes('G33') && plan.threading?.status === CAM_STATUS.SUPPORTED) errors.push(issue('POST_G33_MISSING', 'В программе отсутствует G33 для рассчитанной резьбы.', 'error', 'export'));
    if (!text.includes('SPOS=AC') && [plan.millingAf, plan.millingPocket, plan.radialDrilling].some(item => item?.status === CAM_STATUS.SUPPORTED)) errors.push(issue('POST_SPOS_MISSING', 'В программе отсутствует SPOS=AC для индексируемых операций C.', 'error', 'export'));
    if (plan.millingPocket?.status === CAM_STATUS.SUPPORTED && !/\bY-?\d/.test(text)) errors.push(issue('POST_Y_MISSING', 'В программе отсутствуют команды Y для рассчитанного кармана/паза.', 'error', 'export'));
    return {
      status: errors.length ? CAM_STATUS.BLOCKED : CAM_STATUS.GENERATED,
      controller: 'SINUMERIK 828D', dialect: 'SIEMENS', programName: config.programName,
      errors, lines, text, trace, checksum: `FNV1A32:${fnv1a32(text)}`,
      statistics: { lineCount: lines.length, mappedMoveCount: mappedMoves.size, cuttingMoveCount: cuttingMoves.length },
      notes: [
        'G33 longitudinal thread pitch is emitted in K.',
        'C-indexing is emitted with blocking SPOS=AC positioning.',
        'Peck drilling is expanded into deterministic G0/G1 moves to avoid cycle-version ambiguity.',
        'Radial drilling, AF and pocket milling use live tooling plus blocking C-axis positioning.',
        'X/Y/Z pocket paths are expanded into deterministic G0/G1 moves.',
        'Cutoff is emitted as a deterministic radial G1 move at a fixed Z and must remain the last route operation.',
      ],
    };
  }
}
